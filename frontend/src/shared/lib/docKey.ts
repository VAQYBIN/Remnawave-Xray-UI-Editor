/**
 * Ключ документа в локальных хранилищах (черновики, история, позиции узлов).
 *
 * Uuid конфиг-профиля и uuid шаблона подписки живут в разных пространствах
 * панели и могут совпасть: без вида документа черновик одного открылся бы в
 * другом, а позиции узлов графа перемешались бы. Бэкенд разводит те же
 * пространства каталогами бэкапов (`DATA_DIR/backups/templates/<uuid>/`),
 * фронтенд — этим префиксом.
 *
 * В URL бэкапов уходит по-прежнему голый uuid (`ConfigDraft.docKey`): префикс
 * сломал бы запрос к бэкенду.
 */
export type DocKind = 'profile' | 'template'

/**
 * Вид, которым помечены все записи, созданные до появления шаблонов подписки:
 * тогда редактор работал только с профилями. На него же опираются миграции
 * persist-хранилищ.
 */
export const LEGACY_DOC_KIND: DocKind = 'profile'

export function docStorageKey(kind: DocKind, uuid: string): string {
  return `${kind}:${uuid}`
}

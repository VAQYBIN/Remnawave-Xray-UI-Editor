// Зеркало серверной схемы backend/src/routes/nameSchema.ts, которая зеркалит
// требование панели Remnawave (проверено на живой 3.4.3: панель отвечает 400
// "Name can only contain letters, numbers, underscores, dashes and spaces",
// pattern /^[A-Za-z0-9_\s-]+$/) — общая регулярка для имени профиля и имени
// шаблона подписки. Расширять набор символов нельзя: панель всё равно
// откажет, только позже и по-английски.
//
// Границы длины 2–30 здесь совпадают с серверной схемой (.min(2).max(30)) —
// это не самостоятельное ограничение фронтенда, а то же число, продублированное
// для мгновенной обратной связи в форме до похода на бэкенд.
export const NAME_RE = /^[A-Za-z0-9_\s-]{2,30}$/

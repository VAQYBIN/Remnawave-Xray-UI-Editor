import { describe, expect, it } from 'vitest'
import { formatBytes, groupDigits } from '../src/shared/lib/format'

describe('группировка разрядов', () => {
  it('разделитель — узкий НЕРАЗРЫВНЫЙ пробел, а не обычный', () => {
    // Через рендер это не проверяется вовсе: testing-library нормализует любой
    // пробельный символ в обычный, и проверка `getByText('15 511')` остаётся
    // зелёной при подмене разделителя на обычный пробел. А подмена не
    // безобидна: браузер вправе порвать строку ровно между разрядами
    expect(groupDigits(15_511)).toBe('15\u202F511')
    expect(groupDigits(15_511)).not.toBe('15 511')
  })

  it('число короче четырёх разрядов не трогается', () => {
    expect(groupDigits(511)).toBe('511')
    expect(groupDigits(0)).toBe('0')
  })

  it('группы считаются с конца, а не с начала', () => {
    expect(groupDigits(1_234_567)).toBe('1\u202F234\u202F567')
  })

  it('знак сохраняется', () => {
    expect(groupDigits(-1234)).toBe('-1\u202F234')
  })
})

describe('размер файла', () => {
  it('байты, килобайты и мегабайты — по порогам', () => {
    // Наборы бывают и в килобайтах (домены), и в мегабайтах (подсети крупных
    // стран), поэтому единица выбирается, а не задана одна на всё
    expect(formatBytes(512)).toBe('512 Б')
    expect(formatBytes(4096)).toBe('4 КБ')
    expect(formatBytes(3 * 1024 * 1024)).toBe('3.0 МБ')
  })
})
